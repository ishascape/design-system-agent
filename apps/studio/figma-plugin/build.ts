/**
 * Writes the Figma plugin's code.js from the shared variables script in @dsa/gen-figma, so the
 * plugin and the Figma MCP route always run the same code. Run: npm run build:figma-plugin
 */
import { writeFileSync } from 'node:fs';
import { variablesScriptBody } from '@dsa/gen-figma';

export function renderPluginCode(): string {
  const body = variablesScriptBody()
    .split('\n')
    .map((l) => (l ? `  ${l}` : l))
    .join('\n');
  return `// Generated by apps/studio/figma-plugin/build.ts from packages/gen-figma/src/plugin/variables.js. Do not edit.
/* global figma, __html__ */
figma.showUI(__html__, { width: 440, height: 560, themeColors: true });

async function apply(PAYLOAD) {
${body}
}

figma.ui.onmessage = async (msg) => {
  if (!msg || typeof msg !== 'object') return;
  if (msg.type === 'apply') {
    try {
      const result = await apply(msg.payload);
      figma.ui.postMessage({ type: 'done', result });
    } catch (e) {
      figma.ui.postMessage({ type: 'error', message: String((e && e.message) || e) });
    }
  } else if (msg.type === 'close') {
    figma.closePlugin();
  }
};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL('./code.js', import.meta.url), renderPluginCode());
  process.stdout.write('Wrote apps/studio/figma-plugin/code.js\n');
}
