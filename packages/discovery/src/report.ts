/**
 * Renders an audit inventory as files for people (markdown) and for tools (DTCG JSON).
 * Output is deterministic: same inventory in, same bytes out.
 */
import type { AuditInventory, HardCodedValue, TokenCandidate } from '@dsa/registry';

const ref = (r: { file: string; line: number }) => `${r.file}:${r.line}`;

const DTCG_TYPE: Record<TokenCandidate['type'], string | undefined> = {
  color: 'color',
  dimension: 'dimension',
  fontFamily: 'fontFamily',
  duration: 'duration',
  cubicBezier: 'cubicBezier',
  number: 'number',
  other: undefined,
};

/** Draft DTCG tokens, grouped by type. Provenance goes in $extensions so tools can trace every value. */
export function toDtcgCandidates(inv: AuditInventory): Record<string, unknown> {
  const groups: Record<string, Record<string, unknown>> = {};
  for (const t of inv.tokens) {
    const group = (groups[t.type] ??= {});
    const dtcgType = DTCG_TYPE[t.type];
    group[t.id] = {
      ...(dtcgType ? { $type: dtcgType } : {}),
      $value: t.value,
      ...(t.comment ? { $description: t.comment } : {}),
      $extensions: {
        'dev.dsa.provenance': {
          source: ref(t.source),
          confidence: t.confidence,
          usageCount: t.usageCount,
          commit: inv.source.commit,
        },
        ...(t.overrides.length
          ? {
              'dev.dsa.responsive': t.overrides.map((o) => ({ media: o.media, value: o.value, source: ref(o.source) })),
            }
          : {}),
      },
    };
  }
  return groups;
}

function occurrenceSummary(h: HardCodedValue, max = 3): string {
  const shown = h.occurrences.slice(0, max).map(ref).join(', ');
  return h.occurrences.length > max ? `${shown}, +${h.occurrences.length - max} more` : shown;
}

export function renderDriftReport(inv: AuditInventory): string {
  const colors = inv.hardCoded.filter((h) => h.kind === 'color');
  const lengths = inv.hardCoded.filter((h) => h.kind === 'length');
  const count = (xs: HardCodedValue[], c: HardCodedValue['classification']) =>
    xs.filter((x) => x.classification === c).reduce((n, x) => n + x.occurrences.length, 0);
  const total = (xs: HardCodedValue[]) => xs.reduce((n, x) => n + x.occurrences.length, 0);

  const table = (xs: HardCodedValue[]) =>
    [
      '| Value | Uses | Class | Nearest token | Where |',
      '| --- | --- | --- | --- | --- |',
      ...xs.map(
        (h) =>
          `| \`${h.normalized}\` | ${h.occurrences.length} | ${h.classification} | ${h.nearestToken ? `\`--${h.nearestToken.id}\` (${h.nearestToken.value}, distance ${h.nearestToken.distance})` : ''} | ${occurrenceSummary(h)} |`,
      ),
    ].join('\n');

  return `# Drift report: ${inv.source.id}

Source: ${inv.source.repo} at \`${inv.source.commit.slice(0, 7)}\`. Generated by the audit tool; do not edit by hand.

Values written directly in CSS instead of through a token. Classes are inferred by rule:
**matches-token** has the same value as a token (it may or may not mean the same thing),
**near-token** is within a small tolerance (colour distance 12, or 2px) and is likely drift,
**one-off** has no close token.

## Summary

| Kind | Distinct values | Uses | matches-token | near-token | one-off |
| --- | --- | --- | --- | --- | --- |
| Colour | ${colors.length} | ${total(colors)} | ${count(colors, 'matches-token')} | ${count(colors, 'near-token')} | ${count(colors, 'one-off')} |
| Length (px) | ${lengths.length} | ${total(lengths)} | ${count(lengths, 'matches-token')} | ${count(lengths, 'near-token')} | ${count(lengths, 'one-off')} |

## Colours

${table(colors)}

## Lengths

${table(lengths)}
`;
}

export function renderComponentsReport(inv: AuditInventory): string {
  const reusable = inv.components.filter((c) => c.reusable);
  const single = inv.components.filter((c) => !c.reusable && c.kind === 'component');
  const states = inv.components.filter((c) => c.kind === 'state');
  const graphics = inv.components.filter((c) => c.kind === 'graphic');
  const rows = reusable.map(
    (c) =>
      `| \`${c.id}\` | ${c.usedIn.length} | ${c.usageCount} | ${c.elements.join(', ')} | ${c.modifiers.join(', ') || '–'} | ${c.states.join(', ') || '–'} | ${c.styles.map(ref).join(', ') || '–'} |`,
  );
  const notes = reusable.flatMap((c) => c.notes.map((n) => `- \`${c.id}\`: ${n}`));
  return `# Component candidates: ${inv.source.id}

Source: ${inv.source.repo} at \`${inv.source.commit.slice(0, 7)}\`. Generated by the audit tool; do not edit by hand.

A block counts as **reusable** when it is used in two or more component files. That is a rule, so every
row is *inferred*; the final component list needs human approval.

## Reusable candidates (${reusable.length})

| Block | Files | Uses | Elements | Modifiers | Styled states | Base style |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

## Notes

${notes.length ? notes.join('\n') : 'None.'}

## Used in one file only (${single.length})

${single.map((c) => `\`${c.id}\``).join(', ')}

## Not components

State classes (${states.length}): ${states.map((c) => `\`${c.id}\``).join(', ') || 'none'}

SVG drawing classes (${graphics.length}): ${graphics.map((c) => `\`${c.id}\``).join(', ') || 'none'}
`;
}
